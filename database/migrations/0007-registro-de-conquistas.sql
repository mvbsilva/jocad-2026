BEGIN;
CREATE TABLE IF NOT EXISTS public.medal_awards (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 course text NOT NULL REFERENCES public.medals(course),
 category text NOT NULL CHECK (category IN ('sport','culture','legacy')),
 activity text NOT NULL CHECK (length(btrim(activity)) BETWEEN 2 AND 160),
 gender text NOT NULL DEFAULT '' CHECK (gender IN ('','Feminino','Masculino','Misto')),
 medal_type text NOT NULL CHECK (medal_type IN ('gold','silver')),
 match_id text REFERENCES public.matches(id),
 description text NOT NULL CHECK (length(btrim(description)) BETWEEN 10 AND 3000),
 status text NOT NULL DEFAULT 'confirmed' CHECK (status IN ('confirmed','cancelled')),
 awarded_at timestamptz NOT NULL DEFAULT now(),
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 created_by uuid REFERENCES auth.users(id),
 updated_by uuid REFERENCES auth.users(id)
);
CREATE UNIQUE INDEX IF NOT EXISTS medal_awards_one_per_prize
ON public.medal_awards (category, lower(btrim(activity)), gender, medal_type)
WHERE status='confirmed' AND category <> 'legacy';
CREATE INDEX IF NOT EXISTS medal_awards_course_idx ON public.medal_awards(course,status);

-- Preserva os totais anteriores, caso já existam, como registros históricos sem atribuir modalidade fictícia.
INSERT INTO public.medal_awards(course,category,activity,medal_type,description)
SELECT m.course,'legacy','Saldo anterior sem detalhamento',x.medal_type,
 'Medalha existente antes da implantação do registro individual; origem não detalhada.'
FROM public.medals m CROSS JOIN LATERAL (
 SELECT 'gold'::text medal_type, generate_series(1,LEAST(GREATEST(m.gold,0),1000)) n
 UNION ALL SELECT 'silver', generate_series(1,LEAST(GREATEST(m.silver,0),1000))
) x
WHERE NOT EXISTS(SELECT 1 FROM public.medal_awards a WHERE a.category='legacy' AND a.course=m.course);
-- Segurança: falha em vez de descartar silenciosamente saldos muito altos.
DO $$ BEGIN
 IF EXISTS(SELECT 1 FROM public.medals WHERE gold>1000 OR silver>1000) THEN
  RAISE EXCEPTION 'Saldo anterior superior a 1000; revise antes de migrar';
 END IF;
END $$;

-- Trigger por statement: evita acessar NEW/OLD inexistentes em DELETE/INSERT.
CREATE OR REPLACE FUNCTION public.jocad_recount_medals_v28() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
 UPDATE public.medals m SET
  gold=(SELECT count(*) FROM public.medal_awards a WHERE a.course=m.course AND a.status='confirmed' AND a.medal_type='gold'),
  silver=(SELECT count(*) FROM public.medal_awards a WHERE a.course=m.course AND a.status='confirmed' AND a.medal_type='silver'),
  updated_at=now(), updated_by=auth.uid();
 RETURN NULL;
END $$;
DROP TRIGGER IF EXISTS medal_awards_recount ON public.medal_awards;
CREATE TRIGGER medal_awards_recount AFTER INSERT OR UPDATE OR DELETE ON public.medal_awards
FOR EACH STATEMENT EXECUTE FUNCTION public.jocad_recount_medals_v28();

CREATE OR REPLACE FUNCTION public.jocad_award_audit_v28() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
 IF TG_OP='INSERT' THEN
  INSERT INTO public.audit_log(actor,entity,record_key,old_data,new_data)
  VALUES(auth.uid(),'medal_awards',NEW.id::text,NULL,to_jsonb(NEW));
  RETURN NEW;
 ELSIF TG_OP='UPDATE' THEN
  NEW.updated_at=now(); NEW.updated_by=auth.uid();
  INSERT INTO public.audit_log(actor,entity,record_key,old_data,new_data)
  VALUES(auth.uid(),'medal_awards',NEW.id::text,to_jsonb(OLD),to_jsonb(NEW));
  RETURN NEW;
 END IF;
 RETURN OLD;
END $$;
DROP TRIGGER IF EXISTS medal_awards_audit ON public.medal_awards;
CREATE TRIGGER medal_awards_audit BEFORE INSERT OR UPDATE ON public.medal_awards
FOR EACH ROW EXECUTE FUNCTION public.jocad_award_audit_v28();

ALTER TABLE public.medal_awards ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS medal_awards_public_read ON public.medal_awards;
CREATE POLICY medal_awards_public_read ON public.medal_awards FOR SELECT TO anon,authenticated USING (true);
DROP POLICY IF EXISTS medal_awards_staff_insert ON public.medal_awards;
CREATE POLICY medal_awards_staff_insert ON public.medal_awards FOR INSERT TO authenticated WITH CHECK (public.is_staff() AND created_by=auth.uid() AND status='confirmed');
DROP POLICY IF EXISTS medal_awards_staff_update ON public.medal_awards;
CREATE POLICY medal_awards_staff_update ON public.medal_awards FOR UPDATE TO authenticated USING (public.is_staff()) WITH CHECK (public.is_staff());
GRANT SELECT ON public.medal_awards TO anon,authenticated;
GRANT INSERT,UPDATE ON public.medal_awards TO authenticated;
GRANT USAGE,SELECT ON SEQUENCE public.medal_awards_id_seq TO authenticated;
-- Nenhuma política DELETE: registros são cancelados, não apagados.
COMMIT;
