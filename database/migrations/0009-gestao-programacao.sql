CREATE TABLE IF NOT EXISTS public.schedule_activities (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 day text NOT NULL CHECK (day IN ('24','25','26','27')),
 start_time time NOT NULL,
 end_time time,
 title text NOT NULL CHECK (length(btrim(title)) BETWEEN 2 AND 180),
 category text NOT NULL CHECK (category IN ('Cultura','Esportes','Jogos','Alimentação','Institucional')),
 place text NOT NULL CHECK (length(btrim(place)) BETWEEN 2 AND 160),
 status text NOT NULL DEFAULT 'Programada' CHECK (status IN ('Programada','Em andamento','Concluída','Cancelada')),
 description text NOT NULL DEFAULT '' CHECK (length(description)<=1000),
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 created_by uuid REFERENCES auth.users(id),
 updated_by uuid REFERENCES auth.users(id),
 CONSTRAINT schedule_time_order CHECK (end_time IS NULL OR end_time>start_time)
);
CREATE INDEX IF NOT EXISTS schedule_activities_day_time_idx ON public.schedule_activities(day,start_time,id);
ALTER TABLE public.schedule_activities ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS schedule_public_read ON public.schedule_activities;
CREATE POLICY schedule_public_read ON public.schedule_activities FOR SELECT TO anon,authenticated USING (true);
DROP POLICY IF EXISTS schedule_staff_insert ON public.schedule_activities;
CREATE POLICY schedule_staff_insert ON public.schedule_activities FOR INSERT TO authenticated WITH CHECK (public.is_staff() AND created_by=auth.uid());
DROP POLICY IF EXISTS schedule_staff_update ON public.schedule_activities;
CREATE POLICY schedule_staff_update ON public.schedule_activities FOR UPDATE TO authenticated USING (public.is_staff()) WITH CHECK (public.is_staff());
DROP POLICY IF EXISTS schedule_staff_delete ON public.schedule_activities;
CREATE POLICY schedule_staff_delete ON public.schedule_activities FOR DELETE TO authenticated USING (public.is_staff());
GRANT SELECT ON public.schedule_activities TO anon,authenticated;
GRANT INSERT,UPDATE,DELETE ON public.schedule_activities TO authenticated;
GRANT USAGE,SELECT ON SEQUENCE public.schedule_activities_id_seq TO authenticated;
CREATE OR REPLACE FUNCTION public.jocad_schedule_audit_v35() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
 IF TG_OP='INSERT' THEN
  NEW.created_by=auth.uid(); NEW.updated_by=auth.uid();
  INSERT INTO public.audit_log(actor,entity,record_key,old_data,new_data) VALUES(auth.uid(),'schedule_activities',NEW.id::text,NULL,to_jsonb(NEW));
  RETURN NEW;
 ELSIF TG_OP='UPDATE' THEN
  NEW.updated_at=now(); NEW.updated_by=auth.uid();
  INSERT INTO public.audit_log(actor,entity,record_key,old_data,new_data) VALUES(auth.uid(),'schedule_activities',NEW.id::text,to_jsonb(OLD),to_jsonb(NEW));
  RETURN NEW;
 ELSE
  INSERT INTO public.audit_log(actor,entity,record_key,old_data,new_data) VALUES(auth.uid(),'schedule_activities',OLD.id::text,to_jsonb(OLD),NULL);
  RETURN OLD;
 END IF;
END $$;
DROP TRIGGER IF EXISTS schedule_audit_v35 ON public.schedule_activities;
CREATE TRIGGER schedule_audit_v35 BEFORE INSERT OR UPDATE OR DELETE ON public.schedule_activities FOR EACH ROW EXECUTE FUNCTION public.jocad_schedule_audit_v35();

